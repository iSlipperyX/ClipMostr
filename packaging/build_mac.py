"""Build ClipMonster for Mac: the programs it brings, the icon, `dist/ClipMonster.app`, and a .dmg to download.

Run on a Mac with the app's requirements installed (`pip install -e ".[mac,build]"`) and Xcode's command line
tools (and CMake) for whisper.cpp and llama.cpp:

    python packaging/build_mac.py                              # dist/ClipMonster-mac.dmg (Apple silicon)
    python packaging/build_mac.py --name ClipMonster-mac-intel.dmg     # on an Intel Mac

It gathers what the app runs into build/mac-tools (--tools): ffmpeg (imageio-ffmpeg's, which has the Mac's
media engine), Deno (the deno package's, for YouTube) and whisper.cpp and llama.cpp, built for the Mac's
graphics (Metal) on Apple silicon and for the CPU on an Intel Mac, unless that build is there already (the
workflows keep them in their cache). The release workflow runs it on GitHub's Mac runners.

The app is signed ad hoc, not with an Apple Developer ID, so the first time it's opened macOS asks: System
Settings → Privacy & Security → Open Anyway (or right-click → Open on older macOS).
"""

from __future__ import annotations

import argparse
import os
import platform
import shutil
import stat
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
APP = "ClipMonster"
ICON_SIZES = (16, 32, 64, 128, 256, 512, 1024)
TOOLS = ROOT / "build" / "mac-tools"


def make_icon(out: Path) -> Path:
    """The app icon as .icns, drawn by the app's own theme at every size macOS asks for."""
    os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
    sys.path.insert(0, str(ROOT))
    from PySide6.QtGui import QGuiApplication

    from ytclip.gui.theme import app_icon_pixmap

    app = QGuiApplication.instance() or QGuiApplication([])  # noqa: F841 - pixmaps need it
    with tempfile.TemporaryDirectory() as d:
        iconset = Path(d) / "icon.iconset"
        iconset.mkdir()
        for size in ICON_SIZES:
            if size <= 512:
                app_icon_pixmap(size).save(str(iconset / f"icon_{size}x{size}.png"), "PNG")
            if size >= 32:
                half = size // 2
                app_icon_pixmap(size).save(str(iconset / f"icon_{half}x{half}@2x.png"), "PNG")
        subprocess.run(["iconutil", "-c", "icns", str(iconset), "-o", str(out)], check=True)
    return out


def write_build_info(version: str) -> None:
    """Which build this is: a dev build's own number ("3.6.0+dev.4"), its commit, and where its updates come
    from, as build.py writes it for Windows."""
    sys.path.insert(0, str(ROOT))
    import ytclip

    own = version if version and version != ytclip.__version__ else ""
    (ROOT / "ytclip" / "_build_info.py").write_text(
        f'"""Generated by build_mac.py - do not edit."""\n\nUPDATE_REPO = {os.environ.get("GITHUB_REPOSITORY", "")!r}\n'
        f'BUILD_COMMIT = {os.environ.get("GITHUB_SHA", "")!r}\nBUILD_VERSION = {own!r}\n', encoding="utf-8")


def _copy_program(src: Path, dest: Path) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dest)
    dest.chmod(dest.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


BUILT = (("whisper-cpp", "whisper-cli", "build_whisper_cpp.py", "whisper.cpp"),
         ("llama-cpp", "llama-server", "build_llama_cpp.py", "llama.cpp"))


def _wanted(script: str, project: str, metal: bool) -> str:
    """The VERSION.txt a build of `script` writes ("whisper.cpp v1.9.5 (Metal)"), from the tag it pins."""
    import runpy

    tag = runpy.run_path(str(HERE / script))["TAG"]
    return f"{project} {tag}{' (Metal)' if metal else ''}"


def gather_tools(tools: Path, build_missing: bool = True) -> list[str]:
    """Everything ClipMonster.app runs, in `tools` as the spec collects it. Returns what's still missing.

    ffmpeg and Deno are copied from their packages every time, so an upgraded one is never left behind.
    whisper.cpp and llama.cpp are built when they're missing or were built from another tag (VERSION.txt)."""
    import imageio_ffmpeg

    ffmpeg = tools / "ffmpeg" / "ffmpeg"
    _copy_program(Path(imageio_ffmpeg.get_ffmpeg_exe()), ffmpeg)
    out = subprocess.run([str(ffmpeg), "-hide_banner", "-encoders"], capture_output=True, text=True)
    if "h264_videotoolbox" not in out.stdout:
        print("WARNING: this ffmpeg can't use the Mac's media engine (VideoToolbox): exports use the CPU")
    try:
        import deno
    except ImportError:
        raise SystemExit("The deno package isn't installed: pip install -e \".[mac,build]\"") from None
    _copy_program(Path(deno.find_deno_bin()), tools / "deno" / "deno")
    metal = platform.machine() == "arm64"  # an Intel Mac's graphics: the CPU is the surer bet
    for folder, name, script, project in BUILT:
        made, version = tools / folder / name, tools / folder / "VERSION.txt"
        wanted = _wanted(script, project, metal)
        current = made.is_file() and version.is_file() and version.read_text(encoding="utf-8").strip() == wanted
        if not current and build_missing:
            print(f"Building {wanted} into {tools / folder}", flush=True)
            subprocess.run([sys.executable, str(HERE / script), str(tools / folder)] + (["--metal"] if metal else []),
                           check=True, cwd=ROOT)
        elif not current and made.is_file():
            print(f"WARNING: {made} isn't {wanted}")
    return [f"{folder}/{name}" for folder, name in (("ffmpeg", "ffmpeg"), ("deno", "deno"),
                                                    ("whisper-cpp", "whisper-cli"), ("llama-cpp", "llama-server"))
            if not (tools / folder / name).is_file()]


def build(dmg_name: str, version: str = "", tools: Path = TOOLS, build_missing: bool = True) -> Path:
    write_build_info(version)
    missing = gather_tools(tools, build_missing)
    if missing:
        print(f"WARNING: building without {', '.join(missing)}")
    make_icon(HERE / "clipmonster.icns")
    dist, work = ROOT / "dist", ROOT / "build" / "mac"
    shutil.rmtree(dist / f"{APP}.app", ignore_errors=True)
    shutil.rmtree(dist / APP, ignore_errors=True)
    env = {**os.environ, "CLIPMONSTER_MAC_TOOLS": str(tools)}
    subprocess.run([sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean", "--distpath", str(dist),
                    "--workpath", str(work), str(HERE / "ClipMonsterMac.spec")], check=True, cwd=ROOT, env=env)
    app = dist / f"{APP}.app"
    if not app.is_dir():
        raise SystemExit(f"PyInstaller didn't make {app}")
    # Ad hoc signature over the whole bundle, so Apple silicon runs it and Gatekeeper sees one signed app
    subprocess.run(["codesign", "--force", "--deep", "--sign", "-", str(app)], check=True)
    dmg = dist / dmg_name
    dmg.unlink(missing_ok=True)
    with tempfile.TemporaryDirectory() as d:
        stage = Path(d) / APP
        stage.mkdir()
        subprocess.run(["ditto", str(app), str(stage / f"{APP}.app")], check=True)
        (stage / "Applications").symlink_to("/Applications")  # drag the app onto it
        subprocess.run(["hdiutil", "create", "-volname", APP, "-srcfolder", str(stage), "-ov", "-format", "UDZO",
                        str(dmg)], check=True)
    print(f"built {dmg} ({dmg.stat().st_size / 1e6:.1f} MB)")
    return dmg


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--name", default="ClipMonster-mac.dmg", help="the .dmg's file name")
    ap.add_argument("--version", default="", help="this build's version (a dev build's own number)")
    ap.add_argument("--tools", type=Path, default=TOOLS, help="where the programs it brings are gathered")
    ap.add_argument("--no-build-tools", action="store_true",
                    help="don't build whisper.cpp or llama.cpp when they're missing (the app goes without)")
    args = ap.parse_args()
    build(args.name, args.version, args.tools, not args.no_build_tools)
