"""Build ClipMonster Remote for macOS: the icon, `dist/ClipMonster Remote.app`, and a .dmg to download.

Run on a Mac with the app's requirements installed (`pip install -e ".[mac,build]"`):

    python packaging/build_mac.py                 # dist/ClipMonster-Remote-mac.dmg
    python packaging/build_mac.py --name ClipMonster-Remote-mac-intel.dmg

The release workflow runs it on GitHub's Mac runners. The app is signed ad hoc (PyInstaller does that), not
with an Apple Developer ID, so the first time it's opened macOS asks: System Settings → Privacy & Security →
Open Anyway (or right-click → Open on older macOS).
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
APP = "ClipMonster Remote"
ICON_SIZES = (16, 32, 64, 128, 256, 512, 1024)


def make_icon(out: Path) -> Path:
    """The app icon as .icns, drawn by the app's own theme at every size macOS asks for."""
    os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
    sys.path.insert(0, str(ROOT))
    from PySide6.QtGui import QGuiApplication

    from ytclip.gui.theme import app_icon_pixmap

    app = QGuiApplication.instance() or QGuiApplication([])  # noqa: F841 - pixmaps need it
    with tempfile.TemporaryDirectory() as d:
        iconset = Path(d) / "icon.iconset"
        iconset.mkdir()
        for size in ICON_SIZES:
            if size <= 512:
                app_icon_pixmap(size).save(str(iconset / f"icon_{size}x{size}.png"), "PNG")
            if size >= 32:
                half = size // 2
                app_icon_pixmap(size).save(str(iconset / f"icon_{half}x{half}@2x.png"), "PNG")
        subprocess.run(["iconutil", "-c", "icns", str(iconset), "-o", str(out)], check=True)
    return out


def write_build_info(version: str) -> None:
    """A dev build's own number ("3.6.0+dev.4"), as build.py writes it for Windows."""
    sys.path.insert(0, str(ROOT))
    import ytclip

    own = version if version and version != ytclip.__version__ else ""
    (ROOT / "ytclip" / "_build_info.py").write_text(
        f'"""Generated by build_mac.py - do not edit."""\n\nUPDATE_REPO = ""\nBUILD_COMMIT = '
        f'{os.environ.get("GITHUB_SHA", "")!r}\nBUILD_VERSION = {own!r}\n', encoding="utf-8")


def build(dmg_name: str, version: str = "") -> Path:
    if version:
        write_build_info(version)
    make_icon(HERE / "clipmonster-remote.icns")
    dist, work = ROOT / "dist", ROOT / "build" / "mac"
    shutil.rmtree(dist / f"{APP}.app", ignore_errors=True)
    shutil.rmtree(dist / APP, ignore_errors=True)
    subprocess.run([sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean", "--distpath", str(dist),
                    "--workpath", str(work), str(HERE / "ClipMonsterRemote.spec")], check=True, cwd=ROOT)
    app = dist / f"{APP}.app"
    if not app.is_dir():
        raise SystemExit(f"PyInstaller didn't make {app}")
    # Ad hoc signature over the whole bundle, so Apple silicon runs it and Gatekeeper sees one signed app
    subprocess.run(["codesign", "--force", "--deep", "--sign", "-", str(app)], check=True)
    dmg = dist / dmg_name
    dmg.unlink(missing_ok=True)
    with tempfile.TemporaryDirectory() as d:
        stage = Path(d) / APP
        stage.mkdir()
        subprocess.run(["ditto", str(app), str(stage / f"{APP}.app")], check=True)
        (stage / "Applications").symlink_to("/Applications")  # drag the app onto it
        subprocess.run(["hdiutil", "create", "-volname", APP, "-srcfolder", str(stage), "-ov", "-format", "UDZO",
                        str(dmg)], check=True)
    print(f"built {dmg} ({dmg.stat().st_size / 1e6:.1f} MB)")
    return dmg


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--name", default="ClipMonster-Remote-mac.dmg", help="the .dmg's file name")
    ap.add_argument("--version", default="", help="this build's version (a dev build's own number)")
    args = ap.parse_args()
    build(args.name, args.version)
