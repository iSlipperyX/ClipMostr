"""Build the Windows app: dist/ClipMonster/ClipMonster.exe (+ ytclip.exe), a .zip of it (what installed
copies update from) and, when Inno Setup 6 is installed, the installer dist/ClipMonster-Setup.exe.

    pip install -e .[ai,whisper,build]
    python build.py                          (--installer: fail if Inno Setup isn't there)
    python build.py --version 2.8.0+dev.3    (a dev build: its own version number)

Releases and dev builds are built by GitHub Actions (.github/workflows/release.yml).
"""

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PACKAGING = ROOT / "packaging"
DIST = ROOT / "dist"
ZIP_NAME = "ClipMonster-windows.zip"  # the updater looks for exactly these asset names
SETUP_NAME = "ClipMonster-Setup.exe"


def app_running() -> bool:
    """Windows locks a running exe's files, so a rebuild would fail halfway through."""
    if sys.platform != "win32":
        return False
    out = subprocess.run(["tasklist", "/FI", "IMAGENAME eq ClipMonster.exe"], capture_output=True, text=True).stdout
    return "ClipMonster.exe" in out


def source_version() -> str:
    text = (ROOT / "ytclip" / "__init__.py").read_text(encoding="utf-8")
    return re.search(r'^__version__ = "([^"]+)"', text, re.M)[1]


def update_repo() -> str:
    """owner/repo the auto-updater should watch: GitHub Actions says so directly; locally
    it comes from the git remote. Empty means updates stay off until set in Settings."""
    if os.environ.get("GITHUB_REPOSITORY"):
        return os.environ["GITHUB_REPOSITORY"]
    try:
        url = subprocess.run(["git", "remote", "get-url", "origin"], capture_output=True, text=True, cwd=ROOT).stdout
    except OSError:
        return ""
    m = re.search(r"github\.com[:/]([\w.-]+/[\w.-]+?)(?:\.git)?\s*$", url)
    return m.group(1) if m else ""


def commit() -> str:
    if os.environ.get("GITHUB_SHA"):
        return os.environ["GITHUB_SHA"]
    try:
        return subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True, cwd=ROOT).stdout.strip()
    except OSError:
        return ""


def write_build_info(version: str) -> str:
    repo = update_repo()
    own = version if version != source_version() else ""  # only a dev build has its own number
    (ROOT / "ytclip" / "_build_info.py").write_text(
        f'"""Generated by build.py - do not edit."""\n\nUPDATE_REPO = {repo!r}\nBUILD_COMMIT = {commit()!r}\n'
        f'BUILD_VERSION = {own!r}\n', encoding="utf-8")
    return repo


def numeric_version(version: str) -> str:
    """'2.8.0+dev.3' -> '2.8.0.3', '2.8.0-beta.1' -> '2.8.0.1': Windows' four-number file version."""
    nums = [int(x) for x in re.findall(r"\d+", version)][:4]
    return ".".join(str(n) for n in nums + [0] * (4 - len(nums)))


def write_version_info(version: str) -> None:
    """Windows file properties (Explorer > Properties > Details) for both exes."""
    nums = tuple(int(x) for x in numeric_version(version).split("."))
    (PACKAGING / "version_info.txt").write_text(f"""VSVersionInfo(
  ffi=FixedFileInfo(filevers={nums}, prodvers={nums}, mask=0x3f, flags=0x0, OS=0x40004,
                    fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('CompanyName', 'iSlipperyX'),
      StringStruct('FileDescription', 'ClipMonster'),
      StringStruct('FileVersion', '{version}'),
      StringStruct('InternalName', 'ClipMonster'),
      StringStruct('ProductName', 'ClipMonster'),
      StringStruct('ProductVersion', '{version}')])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
""", encoding="utf-8")


def find_iscc() -> Path | None:
    """Inno Setup's compiler, if it's installed."""
    found = shutil.which("iscc")
    if found:
        return Path(found)
    for base in (os.environ.get("PROGRAMFILES(X86)"), os.environ.get("PROGRAMFILES"), os.environ.get("LOCALAPPDATA")):
        for sub in (("Inno Setup 6",), ("Programs", "Inno Setup 6")):
            if base and (path := Path(base).joinpath(*sub, "ISCC.exe")).is_file():
                return path
    return None


def build_installer(version: str, app_dir: Path) -> Path:
    iscc = find_iscc()
    if iscc is None:
        raise FileNotFoundError("Inno Setup 6 isn't installed (winget install JRSoftware.InnoSetup)")
    subprocess.run([str(iscc), "/Q", f"/DAppVersion={version}", f"/DNumericVersion={numeric_version(version)}",
                    f"/DSourceDir={app_dir}", f"/DOutputDir={DIST}", str(PACKAGING / "ClipMonster.iss")],
                   check=True, cwd=PACKAGING)
    return DIST / SETUP_NAME


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--installer", action="store_true", help="fail if the installer can't be built")
    p.add_argument("--version", default="", help="this build's version (default: ytclip/__init__.py's)")
    args = p.parse_args(argv)
    if app_running():
        print("ClipMonster is running. Close it first: its files can't be replaced while it's open.")
        return 1
    version = args.version or source_version()
    repo = write_build_info(version)
    write_version_info(version)
    print(f"ClipMonster {version}. Auto-updates will follow: "
          f"{('github.com/' + repo) if repo else '(no GitHub repo yet - set one in Settings)'}")
    subprocess.run([sys.executable, str(PACKAGING / "make_icon.py"), str(PACKAGING / "clipmonster.ico")], check=True)
    # Build scratch goes to %TEMP% so OneDrive/Dropbox don't sync thousands of temp files.
    work = Path(tempfile.gettempdir()) / "clipmonster-build"
    try:
        subprocess.run([sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean",
                        "--distpath", str(DIST), "--workpath", str(work), str(PACKAGING / "ClipMonster.spec")],
                       check=True, cwd=ROOT)
    finally:
        shutil.rmtree(work, ignore_errors=True)  # about 1 GB of scratch nothing needs afterwards
    app_dir = DIST / "ClipMonster"
    # Whisper for the graphics card (packaging/build_whisper_cpp.py --vulkan), when it was built
    whisper_cpp = Path(os.environ.get("WHISPER_CPP_DIR") or ROOT / "build" / "whisper-cpp")
    if (whisper_cpp / "whisper-cli.exe").is_file():
        shutil.copytree(whisper_cpp, app_dir / "whisper-cpp", dirs_exist_ok=True)
        print(f"Included whisper.cpp from {whisper_cpp}")
    else:
        print("No whisper.cpp build, so Whisper runs on the CPU only (packaging/build_whisper_cpp.py makes one)")
    archive = shutil.make_archive(str(DIST / ZIP_NAME.removesuffix(".zip")), "zip", DIST, "ClipMonster")
    size = sum(f.stat().st_size for f in app_dir.rglob("*") if f.is_file()) / 1e6
    print(f"\nBuilt {app_dir / 'ClipMonster.exe'} ({size:.0f} MB folder)\nZip: {archive}")
    try:
        setup = build_installer(version, app_dir)
        print(f"Installer: {setup} ({setup.stat().st_size / 1e6:.0f} MB)")
    except FileNotFoundError as exc:
        if args.installer:
            raise SystemExit(f"No installer: {exc}") from exc
        print(f"No installer built: {exc}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
