"""Build the Windows app: dist/ClipMonster/ClipMonster.exe (+ ytclip.exe) and a .zip of it.

    pip install -e .[ai,whisper,build]
    python build.py
"""

import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PACKAGING = ROOT / "packaging"
DIST = ROOT / "dist"


def app_running() -> bool:
    """Windows locks a running exe's files, so a rebuild would fail halfway through."""
    if sys.platform != "win32":
        return False
    out = subprocess.run(["tasklist", "/FI", "IMAGENAME eq ClipMonster.exe"], capture_output=True, text=True).stdout
    return "ClipMonster.exe" in out


def update_repo() -> str:
    """owner/repo the auto-updater should watch: GitHub Actions says so directly; locally
    it comes from the git remote. Empty means updates stay off until set in Settings."""
    if os.environ.get("GITHUB_REPOSITORY"):
        return os.environ["GITHUB_REPOSITORY"]
    try:
        url = subprocess.run(["git", "remote", "get-url", "origin"], capture_output=True, text=True, cwd=ROOT).stdout
    except OSError:
        return ""
    m = re.search(r"github\.com[:/]([\w.-]+/[\w.-]+?)(?:\.git)?\s*$", url)
    return m.group(1) if m else ""


def write_build_info() -> str:
    repo = update_repo()
    (ROOT / "ytclip" / "_build_info.py").write_text(
        f'"""Generated by build.py - do not edit."""\n\nUPDATE_REPO = {repo!r}\n', encoding="utf-8")
    return repo


def main() -> int:
    if app_running():
        print("ClipMonster is running. Close it first: its files can't be replaced while it's open.")
        return 1
    repo = write_build_info()
    print(f"Auto-updates will follow: {('github.com/' + repo) if repo else '(no GitHub repo yet - set one in Settings)'}")
    subprocess.run([sys.executable, str(PACKAGING / "make_icon.py"), str(PACKAGING / "clipmonster.ico")], check=True)
    # Build scratch goes to %TEMP% so OneDrive/Dropbox don't sync thousands of temp files.
    work = Path(tempfile.gettempdir()) / "clipmonster-build"
    subprocess.run([sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean",
                    "--distpath", str(DIST), "--workpath", str(work), str(PACKAGING / "ClipMonster.spec")],
                   check=True, cwd=ROOT)
    app_dir = DIST / "ClipMonster"
    archive = shutil.make_archive(str(DIST / "ClipMonster-windows"), "zip", DIST, "ClipMonster")
    size = sum(f.stat().st_size for f in app_dir.rglob("*") if f.is_file()) / 1e6
    print(f"\nBuilt {app_dir / 'ClipMonster.exe'} ({size:.0f} MB folder)\nZip: {archive}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
